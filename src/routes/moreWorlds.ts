import type { Biome, Difficulty, RouteDef, SectionDef } from './types';
import { bend, climb, descent, hairpins, level, rolling, steady } from './sections';

const pins = (count: number) => hairpins(count, 10, 14);

type Piece =
  | { k: 'flat'; km: number }
  | { k: 'roll'; km: number; amp: number }
  | { k: 'up'; km: number; g: number[]; name: string; pins: number; id: string; inspired: string }
  | { k: 'down'; km: number; pct: number }
  | { k: 'drop'; km: number; pct: number }
  | { k: 'ease'; km: number; pct: number };

interface Seg {
  id: string;
  from: number;
  to: number;
  kind: 'road' | 'tt';
  finish: 'sprint' | 'hill' | 'mountain';
  name: string;
}

interface Spec {
  id: string;
  name: string;
  description: string;
  difficulty: Difficulty;
  seed: number;
  start: number;
  mountain: number;
  tree: number;
  snow: number;
  forest: number;
  water: number | null;
  biome?: Biome;
  pieces: Piece[];
  segments: Seg[];
}

const flat = (km: number): Piece => ({ k: 'flat', km });
const roll = (km: number, amp: number): Piece => ({ k: 'roll', km, amp });
const up = (km: number, g: number[], name: string, hairpinCount: number, id: string, inspired: string): Piece => ({
  k: 'up', km, g, name, pins: hairpinCount, id, inspired,
});
const down = (km: number, pct: number): Piece => ({ k: 'down', km, pct });
const drop = (km: number, pct: number): Piece => ({ k: 'drop', km, pct });
const ease = (km: number, pct: number): Piece => ({ k: 'ease', km, pct });

function build(spec: Spec): RouteDef {
  const sections: SectionDef[] = [];
  const climbs: RouteDef['climbs'] = [];
  spec.pieces.forEach((piece, index) => {
    if (piece.k === 'flat') sections.push(level(piece.km));
    else if (piece.k === 'roll') sections.push(rolling(piece.km, piece.amp, spec.seed + index * 17, bend(40, 300)));
    else if (piece.k === 'up') {
      const style = piece.pins > 0 ? pins(piece.pins) : piece.km < 1.6 ? bend(22, 180) : bend(46, 200);
      sections.push(climb(piece.g, piece.km, style));
      climbs.push({ id: piece.id, name: piece.name, inspiredBy: piece.inspired, fromSection: index, toSection: index });
    } else if (piece.k === 'drop') {
      const style = piece.km < 1.6 ? bend(22, 180) : bend(34, 280);
      sections.push(steady(piece.km, -Math.abs(piece.pct), style));
    } else if (piece.k === 'ease') sections.push(steady(piece.km, piece.pct, bend(26, 420)));
    else sections.push(descent(piece.km, -Math.abs(piece.pct), spec.seed + index * 13, bend(42, 280)));
  });
  return {
    id: spec.id,
    name: spec.name,
    description: spec.description,
    difficulty: spec.difficulty,
    seed: spec.seed,
    startElevation: spec.start,
    sections,
    climbs,
    scenery: {
      mountainHeight: spec.mountain,
      treeline: spec.tree,
      snowline: spec.snow,
      waterLevel: spec.water,
      forestDensity: spec.forest,
      biome: spec.biome,
    },
  };
}

